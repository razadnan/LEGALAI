"""PDF report generation (ReportLab). Developer 3."""
from __future__ import annotations

from datetime import datetime
from io import BytesIO
from pathlib import Path
from typing import Optional
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (KeepTogether, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle)

from core.exceptions import ReportGenerationError
from core.schemas import WorkflowResult

NAVY = colors.HexColor("#1F2A44")
SEVERITY_COLORS = {"high": colors.HexColor("#B42318"), "medium": colors.HexColor("#B54708"),
                   "low": colors.HexColor("#027A48")}
DISCLAIMER = ("This report was generated by an AI-assisted tool for informational purposes only. It is not legal "
              "advice. Findings may be incomplete or wrong; have a qualified lawyer review the contract.")


def _styles():
    base = getSampleStyleSheet()
    return {
        "title": ParagraphStyle("t", parent=base["Title"], textColor=NAVY, fontSize=22, spaceAfter=4),
        "h1": ParagraphStyle("h1", parent=base["Heading2"], textColor=NAVY, spaceBefore=14, spaceAfter=6),
        "body": ParagraphStyle("b", parent=base["BodyText"], fontSize=9.5, leading=13),
        "small": ParagraphStyle("s", parent=base["BodyText"], fontSize=8, leading=10.5, textColor=colors.HexColor("#475467")),
        "cell": ParagraphStyle("c", parent=base["BodyText"], fontSize=8.5, leading=11),
        "quote": ParagraphStyle("q", parent=base["BodyText"], fontSize=8.5, leading=11, leftIndent=8,
                                textColor=colors.HexColor("#344054")),
    }


def _p(text: Optional[str], style, limit: int = 900) -> Paragraph:
    text = (text or "").strip()
    if len(text) > limit:
        text = text[:limit].rstrip() + "..."
    return Paragraph(escape(text).replace("\n", "<br/>"), style)


def _grid(rows, widths, header=True):
    t = Table(rows, colWidths=widths, repeatRows=1 if header else 0)
    style = [("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#D0D5DD")), ("VALIGN", (0, 0), (-1, -1), "TOP"),
             ("LEFTPADDING", (0, 0), (-1, -1), 5), ("RIGHTPADDING", (0, 0), (-1, -1), 5)]
    if header:
        style += [("BACKGROUND", (0, 0), (-1, 0), NAVY), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white)]
    t.setStyle(TableStyle(style))
    return t


def _footer(canvas, doc):
    canvas.saveState()
    canvas.setFont("Helvetica", 7.5)
    canvas.setFillColor(colors.HexColor("#667085"))
    canvas.drawString(18 * mm, 10 * mm, "LegalMind AI - AI-assisted analysis, not legal advice")
    canvas.drawRightString(A4[0] - 18 * mm, 10 * mm, f"Page {doc.page}")
    canvas.restoreState()


def build_story(result: WorkflowResult) -> list:
    st = _styles()
    width = A4[0] - 36 * mm
    story: list = [Paragraph("LegalMind AI", st["title"]),
                   Paragraph("Legal Document Analysis Report", st["h1"]),
                   _p(f"Generated {datetime.now():%d %B %Y, %H:%M}", st["small"])]

    docs = ", ".join(f"{d.filename} ({d.document_id}, {d.page_count} page(s))" for d in result.documents) or "n/a"
    story += [Spacer(1, 6), _p(f"Document(s): {docs}", st["body"])]
    if result.warnings:
        story += [Spacer(1, 4)] + [_p(f"Note: {w}", st["small"]) for w in result.warnings]

    a = result.analysis
    if a:
        story.append(Paragraph("1. Document overview", st["h1"]))
        story.append(_grid([[_p("Document type", st["cell"]), _p(a.document_type, st["cell"])],
                            [_p("Parties", st["cell"]), _p("; ".join(a.parties) or "Not identified", st["cell"])]],
                           [35 * mm, width - 35 * mm], header=False))
        if a.summary:
            story += [Spacer(1, 6), _p(a.summary, st["body"], 1500)]

        if a.important_dates:
            story.append(Paragraph("2. Important dates", st["h1"]))
            rows = [[_p("Description", st["cell"]), _p("Date", st["cell"]), _p("Page", st["cell"])]]
            rows += [[_p(d.label, st["cell"]), _p(d.date, st["cell"]), _p(str(d.page or "-"), st["cell"])]
                     for d in a.important_dates]
            story.append(_grid(rows, [width - 60 * mm, 40 * mm, 20 * mm]))

        if a.obligations:
            story.append(Paragraph("3. Key obligations", st["h1"]))
            rows = [[_p("Party", st["cell"]), _p("Obligation", st["cell"]), _p("Page", st["cell"])]]
            rows += [[_p(o.party or "-", st["cell"]), _p(o.description, st["cell"], 500), _p(str(o.page or "-"), st["cell"])]
                     for o in a.obligations]
            story.append(_grid(rows, [35 * mm, width - 55 * mm, 20 * mm]))

    if result.risks:
        story.append(Paragraph("4. Clauses that deserve additional review", st["h1"]))
        for r in result.risks:
            col = SEVERITY_COLORS.get(r.severity, colors.grey)
            head = Paragraph(f'<font color="{col.hexval().replace("0x", "#")}"><b>[{r.severity.upper()}]</b></font> '
                             f"<b>{escape(r.clause or 'Flagged clause')}</b>"
                             f"{f' - page {r.page}' if r.page else ''}", st["body"])
            parts = [head, _p(r.explanation, st["body"])]
            ev_str = r.evidence_text if hasattr(r, "evidence_text") else str(r.evidence or "")
            if ev_str:
                tag = "" if r.verified in (True, None) else " (evidence NOT verified in document)"
                parts.append(_p(f"Evidence{tag}: \"{ev_str}\"", st["quote"], 600))
            if r.lawyer_question:
                parts.append(_p(f"Question for a lawyer: {r.lawyer_question}", st["small"]))
            story += [KeepTogether(parts), Spacer(1, 6)]

    if result.answer and result.question:
        story.append(Paragraph("5. Question and answer", st["h1"]))
        story += [_p(f"Q: {result.question}", st["body"]), _p(f"A: {result.answer.answer}", st["body"], 2000)]
        for s in result.answer.sources:
            ref = ", ".join(x for x in (f"page {s.page}" if s.page else "", f"clause {s.clause}" if s.clause else "") if x)
            tag = " [unverified]" if s.verified is False else ""
            story.append(_p(f"Source ({ref or 'document'}){tag}: \"{s.text}\"", st["quote"], 500))

    if result.comparison:
        story.append(Paragraph("6. Version comparison", st["h1"]))
        story.append(_p(result.comparison.summary, st["body"]))
        if result.comparison.changes:
            rows = [[_p(h, st["cell"]) for h in ("Change", "Section", "Previous", "Revised")]]
            for c in result.comparison.changes:
                rows.append([_p(c.change_type.upper(), st["cell"]), _p(c.section, st["cell"]),
                             _p(c.old_text or "-", st["cell"], 350), _p(c.new_text or "-", st["cell"], 350)])
            story.append(_grid(rows, [22 * mm, 28 * mm, (width - 50 * mm) / 2, (width - 50 * mm) / 2]))

    story += [Spacer(1, 18), _p(DISCLAIMER, st["small"])]
    return story


def generate_report(result: WorkflowResult, output_path: Optional[Path | str] = None) -> bytes:
    """Render the PDF; return bytes and optionally write them to ``output_path``."""
    try:
        buf = BytesIO()
        SimpleDocTemplate(buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=16 * mm,
                          bottomMargin=18 * mm, title="LegalMind AI Report",
                          author="LegalMind AI").build(build_story(result), onFirstPage=_footer, onLaterPages=_footer)
        data = buf.getvalue()
        if output_path:
            Path(output_path).parent.mkdir(parents=True, exist_ok=True)
            Path(output_path).write_bytes(data)
        return data
    except Exception as exc:
        raise ReportGenerationError(f"Report failed: {exc}") from exc
